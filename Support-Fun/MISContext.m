function context = MISContext(in,domain)
% Resolve one integration measure, cached payload and frozen density history.
% Sampling records are retained for inspection; integration records alone
% enter density ratios. No target or model evaluations are performed here.
domain=validatestring(domain,{'bayesian','reliability'});
assert(isstruct(in) && isscalar(in) && all(isfield(in,{'Nite','x','y','g','intBay'})), ...
    'SeMIS:MISSize','MIS requires a scalar sampled-history structure.');
n=in.Nite;
validateattributes(n,{'numeric'},{'scalar','integer','positive','finite'});
assert(iscell(in.x) && iscell(in.y) && iscell(in.g) && ...
    numel(in.x)==n && numel(in.y)==n && numel(in.g)>=n, ...
    'SeMIS:MISSize','One sampling record and proposal are required per sampled level.');
context=struct('Domain',domain,'Nite',n,'G',{in.g}, ...
    'SamplingX',{in.x},'SamplingYraw',{in.y},'Initial',MISInitialState(in), ...
    'IndependentSamples',MISIndependentSamples(in,n),'ChainLengths',{cell(n,1)}, ...
    'SampleDesign',{cell(n,1)},'SeedInfo',{cell(n,1)});
if isfield(in,'ChainLengths')
    assert(iscell(in.ChainLengths) && numel(in.ChainLengths)==n, ...
        'SeMIS:ChainLayout','Provide one optional chain-length vector per level.');
    context.ChainLengths=in.ChainLengths;
end
if isfield(in,'SeedInfo')
    assert(iscell(in.SeedInfo) && numel(in.SeedInfo)==n, ...
        'SeMIS:SeedHistory','Provide one optional seed record per sampled level.');
    context.SeedInfo=in.SeedInfo;
end
modern=isfield(in,'levels');
if modern
    assert(iscell(in.levels) && numel(in.levels)==n, ...
        'SeMIS:IntegrationHistory','One frozen level is required per sampled proposal.');
end
if isfield(in,'integration')
    rec=in.integration;
    assert(isstruct(rec) && isscalar(rec) && all(isfield(rec,{'x','y','intBay'})), ...
        'SeMIS:IntegrationHistory','Integration history requires x, y and intBay.');
else
    space=ISDSpace(in.intBay);
    if modern || ~strcmp(space.Kind,'identity')
        error('SeMIS:MissingIntegrationHistory', ...
            'A projected history requires its recorded integration samples; sampling records cannot be reinterpreted.');
    end
    rec=struct('x',{in.x},'y',{in.y},'intBay',in.intBay);
end
assert(iscell(rec.x) && iscell(rec.y) && numel(rec.x)==n && numel(rec.y)==n, ...
    'SeMIS:MISSize','Nite differs from integration history.');
context.X=rec.x; context.Yraw=rec.y; context.IntBay=rec.intBay;
context.Views=cell(n,1); context.Models=cell(n,1);
context.Spaces=cell(n,1); context.Descriptors=cell(n,1);
if isfield(rec,'views')
    assert(iscell(rec.views) && numel(rec.views)==n, ...
        'SeMIS:IntegrationHistory','One integration view is required per sampled level.');
end
if isfield(rec,'descriptors')
    assert(iscell(rec.descriptors) && numel(rec.descriptors)==n, ...
        'SeMIS:IntegrationHistory','One space descriptor is required per sampled level.');
end
for k=1:n
    if isfield(in,'SamplerState')&&isstruct(in.SamplerState{k})&&isfield(in.SamplerState{k},'SampleDesign')
        context.SampleDesign{k}=MISSampleDesign(in.SamplerState{k}.SampleDesign,numel(in.x{k})/size(in.x{k},1));
    end
    if modern
        level=in.levels{k};
        if isfield(level,'SamplerState')&&isstruct(level.SamplerState)&&isfield(level.SamplerState,'SampleDesign')
            if isfield(in,'SamplerState')
                assert(isequaln(level.SamplerState.SampleDesign,context.SampleDesign{k}), ...
                    'SeMIS:SampleDesign','Frozen and public sampling designs disagree.');
            else
                context.SampleDesign{k}=MISSampleDesign(level.SamplerState.SampleDesign,numel(in.x{k})/size(in.x{k},1));
            end
        end
        assert(isstruct(level) && isscalar(level) && ...
            all(isfield(level,{'G','model','view','space','descriptor','sampling','integration'})), ...
            'SeMIS:IntegrationHistory','Incomplete frozen level.');
        assert(isfield(rec,'views') && isfield(rec,'descriptors'), ...
            'SeMIS:IntegrationHistory','Modern histories require integration views and descriptors.');
        assert(isequaln(level.G,in.g{k}) && isequaln(level.model.G,in.g{k}) && ...
            isequaln(level.view,rec.views{k}) && ...
            isequaln(level.sampling.x,in.x{k}) && isequaln(level.sampling.y,in.y{k}) && ...
            isequaln(level.integration.x,rec.x{k}) && isequaln(level.integration.y,rec.y{k}), ...
            'SeMIS:IntegrationHistory','Frozen levels and public sample/proposal records disagree.');
        assert(isequaln(level.descriptor,rec.descriptors{k}), ...
            'SeMIS:IntegrationContract','Frozen and public space descriptors disagree.');
        model=level.model; view=level.view; space=level.space; descriptor=level.descriptor;
        assert(isa(space,'ISDSpaceAdapter') && isscalar(space), ...
            'SeMIS:IntegrationContract','Frozen levels require a value space adapter.');
        assert(isequaln(space.Describe(model,view),descriptor), ...
            'SeMIS:IntegrationContract','The frozen adapter disagrees with its space descriptor.');
        if isfield(level,'ChainLengths')
            assert(isequaln(level.ChainLengths,context.ChainLengths{k}), ...
                'SeMIS:IntegrationHistory','Frozen and public chain layouts disagree.');
        end
        if isfield(level,'IndependentSamples') && isfield(in,'IndependentSamples')
            assert(isequaln(level.IndependentSamples,context.IndependentSamples(k)), ...
                'SeMIS:IntegrationHistory','Frozen and public independence flags disagree.');
        end
        if isfield(level,'SeedInfo')
            if isfield(in,'SeedInfo')
                assert(isequaln(level.SeedInfo,context.SeedInfo{k}), ...
                    'SeMIS:SeedHistory','Frozen and public seed records disagree.');
            else
                context.SeedInfo{k}=level.SeedInfo;
            end
        end
    else
        model=in.intBay; model.G=in.g{k}; space=ISDSpace(model);
        if isfield(rec,'views'), view=MISViewAt(rec.views,in.g,k);
        else, view=MISViewAt(rec.intBay,in.g,k); end
        if isfield(rec,'descriptors'), descriptor=rec.descriptors{k};
        else, descriptor=space.Describe(model,view); end
    end
    assert(~isa(model,'handle') && ~isa(view,'handle'), ...
        'SeMIS:MutableHistory','MIS histories require frozen value models and views.');
    assert(isequaln(view.G,in.g{k}),'SeMIS:IntegrationHistory', ...
        'Frozen integration parameters disagree with G.');
    validateDescriptor(descriptor);
    if k>1
        first=context.Descriptors{1};
        assert(isequal(descriptor.integration,first.integration) && ...
            isequal(descriptor.sampling,first.sampling) && isequal(descriptor.output,first.output), ...
            'SeMIS:IntegrationContract','All proposals must share coordinate dimensions and reference measures.');
        assert(size(rec.y{k},1)==size(rec.y{1},1), ...
            'SeMIS:IntegrationContract','Cross-proposal evaluation requires a common integration payload layout.');
    end
    assert(descriptor.integration.dimension==view.Ndim && descriptor.sampling.dimension==model.Ndim, ...
        'SeMIS:IntegrationContract','Coordinate dimensions disagree with the frozen model or view.');
    validateRecord(rec.x{k},rec.y{k},descriptor.integration.dimension);
    validateRecord(in.x{k},in.y{k},descriptor.sampling.dimension);
    if isprop(view,'Nfun')
        assert(size(rec.y{k},1)==view.Nfun,'SeMIS:IntegrationHistory', ...
            'Integration cache rows disagree with the frozen view.');
    end
    if isprop(model,'Nfun')
        assert(size(in.y{k},1)==model.Nfun,'SeMIS:IntegrationHistory', ...
            'Sampling cache rows disagree with the frozen model.');
    end
    assert(isequal(size(rec.y{k},2:3),size(in.y{k},2:3)), ...
        'SeMIS:IntegrationHistory','Projection must retain the sampled particle and chain layout.');
    lengths=context.ChainLengths{k};
    if ~isempty(lengths)
        assert(isnumeric(lengths) && isreal(lengths) && isvector(lengths) && ...
            all(isfinite(lengths) & lengths>0 & lengths==floor(lengths)) && ...
            sum(lengths)==prod(size(rec.y{k},2:3)), ...
            'SeMIS:ChainLayout','Chain lengths must partition all retained integration particles.');
    end
    if ~isempty(context.SeedInfo{k})
        directRecorded=isfield(in,'SamplingMethod') && strcmp(in.SamplingMethod{k},'direct');
        if modern && isfield(in.levels{k},'SamplingMethod')
            directRecorded=directRecorded || strcmp(in.levels{k}.SamplingMethod,'direct');
        end
        assert(k>1 && ~context.IndependentSamples(k) && ~directRecorded, ...
            'SeMIS:SeedHistory','Initial and independent levels cannot carry parent seed records.');
        validateSeedInfo(context.SeedInfo{k},rec.x{k-1},rec.y{k-1},rec.y{k},lengths);
    end
    context.Views{k}=view; context.Models{k}=model;
    context.Spaces{k}=space; context.Descriptors{k}=descriptor;
end
if isfield(context.Initial,'integration')
    assert(isequal(context.Initial.integration,context.Descriptors{1}.integration), ...
        'SeMIS:IntegrationContract','Initial normalizer metadata names another integration measure.');
end
if isfield(context.Initial,'normalizerRelation')
    assert(strcmp(context.Initial.normalizerRelation,'preserved'), ...
        'SeMIS:IntegrationContract','Initial normalizer must be preserved by the space adapter.');
end
context.TF=context.Models{1}.TF;
context.TargetCount=1;
if strcmp(domain,'reliability')
    context.TargetCount=context.TF.Nfun;
    validateattributes(context.TargetCount,{'numeric'},{'scalar','positive','integer','finite'});
end
end

function validateSeedInfo(info,parentX,parentY,currentY,lengths)
required={'parentIndices','parentN','selection','candidateCount','candidateIndices', ...
    'integrationX','integrationY','integrationPreserved','keep','steps','SeedMode'};
assert(isstruct(info) && isscalar(info) && all(isfield(info,required)), ...
    'SeMIS:SeedHistory','Incomplete seed genealogy metadata.');
parentX=reshape(parentX,size(parentX,1),[]);
parentY=reshape(parentY,size(parentY,1),[]);
idx=info.parentIndices;
assert(isnumeric(idx) && isreal(idx) && isrow(idx) && ~isempty(idx) && ...
    all(isfinite(idx) & idx==floor(idx) & idx>=1 & idx<=size(parentX,2)), ...
    'SeMIS:SeedHistory','Parent indices must index the previous flattened integration population.');
assert(isnumeric(info.parentN) && isscalar(info.parentN) && info.parentN==size(parentX,2), ...
    'SeMIS:SeedHistory','Recorded parent population size disagrees with history.');
assert(isequaln(info.integrationX,parentX(:,idx)) && isequaln(info.integrationY,parentY(:,idx)), ...
    'SeMIS:SeedHistory','Recorded integration seeds disagree with selected parent records.');
assert(ischar(info.selection) && ismember(info.selection,{'survivors','weighted','custom'}) && ...
    isnumeric(info.candidateCount) && isscalar(info.candidateCount) && ...
    isfinite(info.candidateCount) && info.candidateCount==floor(info.candidateCount) && ...
    info.candidateCount>=1 && info.candidateCount<=info.parentN, ...
    'SeMIS:SeedHistory','Invalid actual seed selection design.');
pool=info.candidateIndices;
assert(isnumeric(pool) && isreal(pool) && isrow(pool) && ...
    numel(pool)==info.candidateCount && all(isfinite(pool) & ...
    pool==floor(pool) & pool>=1 & pool<=info.parentN) && ...
    numel(unique(pool))==numel(pool) && all(ismember(idx,pool)), ...
    'SeMIS:SeedHistory','Eligible parent indices disagree with the seed selection design.');
if strcmp(info.selection,'survivors')
    assert(numel(unique(idx))==numel(idx) && numel(idx)<=info.candidateCount, ...
        'SeMIS:SeedHistory','Survivor selection must use distinct eligible parents.');
end
assert(ischar(info.keep) && ismember(info.keep,{'all','last'}) && ...
    isnumeric(info.steps) && isreal(info.steps) && isvector(info.steps) && ...
    all(isfinite(info.steps) & info.steps>=1 & info.steps==floor(info.steps)) && ...
    (isscalar(info.steps) || numel(info.steps)==numel(idx)), ...
    'SeMIS:SeedHistory','Invalid retained-chain plan.');
assert(ischar(info.SeedMode) && ismember(info.SeedMode,{'move','retain','reevaluate','unknown'}), ...
    'SeMIS:SeedHistory','Invalid sampler seed mode.');
assert(islogical(info.integrationPreserved) && isscalar(info.integrationPreserved), ...
    'SeMIS:SeedHistory','Integration seed-transport invariance must be an explicit logical scalar.');
if strcmp(info.keep,'last')
    valid=isscalar(info.steps) && isempty(lengths) && ...
        size(currentY,2)==numel(idx) && size(currentY,3)==1;
elseif isempty(lengths)
    valid=isscalar(info.steps) && size(currentY,2)==numel(idx) && ...
        size(currentY,3)==info.steps;
else
    valid=numel(lengths)==numel(idx) && ...
        isequal(lengths(:),info.steps(:)) && size(currentY,3)==1;
end
assert(valid,'SeMIS:SeedHistory','Seed count and retention plan disagree with the retained chain layout.');
end

function validateDescriptor(d)
assert(isstruct(d) && isscalar(d) && ...
    all(isfield(d,{'kind','sampling','integration','output','normalizerRelation','likelihoodDiagnostics'})), ...
    'SeMIS:IntegrationContract','Incomplete integration-space descriptor.');
assert(strcmp(d.normalizerRelation,'preserved') && islogical(d.likelihoodDiagnostics) && isscalar(d.likelihoodDiagnostics), ...
    'SeMIS:IntegrationContract','Space mappings must preserve the integral and declare diagnostic capability.');
for name={'sampling','integration','output'}
    item=d.(name{1});
    assert(isstruct(item) && isscalar(item) && all(isfield(item,{'coordinates','dimension','measure'})), ...
        'SeMIS:IntegrationContract','A space requires coordinates, dimension and measure.');
    assert(isnumeric(item.dimension) && isscalar(item.dimension) && isfinite(item.dimension) && ...
        item.dimension>0 && item.dimension==floor(item.dimension), ...
        'SeMIS:IntegrationContract','Space dimensions must be positive integers.');
    for field={'coordinates','measure'}
        value=item.(field{1});
        assert((ischar(value) && isrow(value) && ~isempty(value)) || ...
            (isstring(value) && isscalar(value) && strlength(value)>0), ...
            'SeMIS:IntegrationContract','Coordinates and measures require nonempty names.');
    end
end
end

function validateRecord(x,y,dimension)
assert(isnumeric(x) && isreal(x) && ndims(x)<=3 && size(x,1)==dimension && ...
    all(isfinite(x),'all') && isnumeric(y) && isreal(y) && ndims(y)<=3 && ...
    size(y,1)>=2 && prod(size(y,2:3))>0 && isequal(size(x,2:3),size(y,2:3)), ...
    'SeMIS:IntegrationHistory','Coordinate and cached-density records have incompatible dimensions or values.');
assert(~any(isnan(y(1:2,:)) | y(1:2,:)==inf,'all'), ...
    'SeMIS:InvalidDensity','Cached proposal log densities must be real finite values or -Inf.');
end
