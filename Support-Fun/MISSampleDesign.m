function design=MISSampleDesign(design,N)
% Explicit fixed allocation; independence is conditional on frozen proposals.
assert(isstruct(design)&&isscalar(design)&&all(isfield(design, ...
    {'kind','labels','counts','conditionalOnFrozenProposals'})), ...
    'SeMIS:SampleDesign','Incomplete direct-sampling design.');
assert(strcmp(design.kind,'stratified-mixture')&& ...
    isequal(design.conditionalOnFrozenProposals,true), ...
    'SeMIS:SampleDesign','Only conditional fixed mixture allocation is supported.');
c=design.counts(:).';a=design.labels(:).';
assert(isnumeric(c)&&isnumeric(a)&&isreal(c)&&isreal(a)&& ...
    all(isfinite(c)&c>=2&c==fix(c))&&sum(c)==N&&numel(a)==N&& ...
    all(isfinite(a)&a>=1&a<=numel(c)&a==fix(a))&& ...
    isequal(accumarray(a(:),1,[numel(c),1]).',c), ...
    'SeMIS:SampleDesign','Counts and component labels must partition all draws, with at least two per stratum.');
design.counts=c;design.labels=a;
end
